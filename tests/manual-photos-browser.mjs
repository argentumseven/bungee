import test from "node:test";
import assert from "node:assert/strict";
import { chromium } from "playwright-core";
import { readFile } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import { fixture } from "./support/server.mjs";
import { phone } from "./support/phone.mjs";

test("manual picture command requires a ready camera capability and displays its labelled photo", async t => {
  const f = await fixture(t), p = await phone(f);
  const browser = await chromium.launch({ executablePath: process.env.CHROME_BIN || "/usr/bin/chromium", headless: true, args: ["--no-sandbox", "--disable-dev-shm-usage"] });
  t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  const [name, value] = f.cookie.split("=");
  await context.addCookies([{ name, value, url: f.origin }]);
  const page = await context.newPage(), errors = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto(f.origin);
  await page.getByRole("button", { name: /^Devices/ }).click();
  const button = page.getByRole("button", { name: /Take picture/ });
  await button.waitFor();
  assert.equal(await button.isDisabled(), true);
  assert.equal((await p.request("/v1/telemetry", { battery: 80, charging: false, device_owner: false, capabilities: ["take_picture"] })).status, 200);
  await page.reload();
  await page.getByRole("button", { name: /^Devices/ }).click();
  await page.screenshot({ path: "work/manual-picture-desktop.png", fullPage: true });
  await button.click();
  const queued = f.sql("SELECT id,kind,device_id,status FROM commands");
  assert.equal(queued.length, 1);
  assert.deepEqual(queued[0].slice(1), ["take_picture", p.id, "pending"]);
  const offered = await (await p.request("/v1/commands", {})).json();
  const photo = { id: randomUUID(), captured_at: Math.floor(Date.now() / 1000), reason: "remote_manual", failed_attempts: 0, jpeg: (await readFile("tests/fixtures/recovery-test.jpg")).toString("base64") };
  assert.equal((await p.request("/v1/photos", { photo_epoch: offered.photo_epoch, photo })).status, 200);
  assert.equal((await p.request("/v1/ack", { id: queued[0][0], status: "executed", result: "Picture captured and queued for upload", attempted_at: photo.captured_at })).status, 200);
  await page.getByRole("button", { name: "Device care", exact: true }).click();
  const image = page.getByRole("img", { name: "Manually requested picture", exact: true });
  await image.waitFor();
  await page.waitForFunction(() => document.querySelector(".recovery-photos img")?.naturalWidth === 320);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole("button", { name: /^Devices/ }).click();
  await button.waitFor();
  await page.screenshot({ path: "work/manual-picture-mobile.png", fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
});
